  await login(bruno, 'bruno@example.test')
  expect((await bruno.put('/api/wishes', { data: { id: wish.id, title: 'No permitido' } })).status()).toBe(403)
  expect((await bruno.post('/api/assignments', { data: { wish_id: wish.id } })).status()).toBe(200)
  expect((await request.delete('/api/assignments?wish_id=' + wish.id)).status()).toBe(403)
  expect((await (await request.get('/api/wishes/assignments?wish_ids=' + wish.id)).json()).data).toEqual([])
  const clara = await playwright.request.newContext({ baseURL: 'http://127.0.0.1:9000' })
  await login(clara, 'clara@example.test')
